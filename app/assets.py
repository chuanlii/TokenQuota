    """一个订阅。

    ``slots`` 声明面板上显示哪几个额度槽位（没有的别占位置），
    ``show_exp`` 声明要不要显示重置卡过期时间。
    """

    def __init__(self, sid: str, name: str, accent: str, icon: str, provider_attr: str,
                 slots: tuple[str, ...] = PERIOD_KEYS, show_exp: bool = False):
        self.id = sid
        self.name = name
        self.accent = accent
        self.icon = icon
        self.provider_attr = provider_attr
        self.slots = tuple(slots)
        self.show_exp = bool(show_exp)


